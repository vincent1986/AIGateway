/** @type {'zh'|'en'} */
let locale = detectLocale();

function detectLocale() {
  try {
    const saved = localStorage.getItem(LOCALE_KEY);
    if (saved && SUPPORTED.includes(saved)) return /** @type {'zh'|'en'} */ (saved);
  } catch (_) {}
  const nav = (navigator.language || "").toLowerCase();
  return nav.startsWith("zh") ? "zh" : "en";
}

export function getLocale() {
  return locale;
}

/** @param {'zh'|'en'|string} next */
export function setLocale(next) {
  if (!SUPPORTED.includes(next)) return locale;
  locale = /** @type {'zh'|'en'} */ (next);
  try {
    localStorage.setItem(LOCALE_KEY, locale);
  } catch (_) {}
  applyDocumentLang();
  return locale;
}

export function applyDocumentLang() {
  if (typeof document === "undefined") return;
  document.documentElement.lang = locale === "zh" ? "zh-CN" : "en";
}

/**
 * @param {string} key
 * @param {Record<string, string|number>=} vars
 */
export function t(key, vars) {
  const table = dict[locale] || dict.zh;
  let s = table[key] ?? dict.zh[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.replaceAll(`{${k}}`, String(v));
    }
  }
  return s;
}

/** Localized “reveal in file manager” label for OS. */
export function revealLabelForOs(os) {
  if (os === "windows") return t("reveal.windows");
  if (os === "linux") return t("reveal.linux");
  return t("reveal.darwin");
}

